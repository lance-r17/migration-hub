export function getSurveyFieldsBySection(): Record<string, SurveyFieldDef[]> {
  const grouped: Record<string, SurveyFieldDef[]> = {}
  for (const def of SURVEY_FIELD_DEFS) {
    if (!grouped[def.sectionLabel]) grouped[def.sectionLabel] = []
    grouped[def.sectionLabel].push(def)
  }
  return grouped
}

/** Lookup a field definition by its ID */
export function getSurveyFieldById(id: string): SurveyFieldDef | undefined {
  return SURVEY_FIELD_DEFS.find(d => d.id === id)
}
